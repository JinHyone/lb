class PGCursor:
    """기존 DB 호출부와 호환되는 최소 커서 인터페이스를 제공한다."""
    def __init__(self, rows=None, rowcount=0):
        self._rows = rows or []
        self.rowcount = rowcount

    async def fetchone(self):
        return self._rows[0] if self._rows else None

    async def fetchall(self):
        return self._rows


class PGConnection:
    def __init__(self, conn):
        self.conn = conn

    @staticmethod
    def _sql(sql: str) -> str:
        # 이 프로젝트의 SQL에는 물음표가 매개변수 자리표시자로만 사용된다.
        index = 0
        def replace(_match):
            nonlocal index
            index += 1
            return f"${index}"
        sql = re.sub(r"\?", replace, sql)
        sql = re.sub(r"INSERT OR IGNORE INTO", "INSERT INTO", sql, flags=re.IGNORECASE)
        if re.search(r"INSERT INTO processed_events\s*\(", sql, flags=re.IGNORECASE) and "ON CONFLICT" not in sql.upper():
            sql = sql.rstrip().rstrip(";") + " ON CONFLICT (event_id) DO NOTHING"
        return sql

    async def execute(self, sql, params=()):
        """Execute SQL while preserving the small cursor API used by this app."""
        sql = self._sql(sql.strip())
        upper = sql.lstrip().upper()
        bound_params = tuple(params) if params else ()

        # Fetching rows directly supports SELECT and DML with RETURNING clauses.
        if upper.startswith(("SELECT", "WITH")) or " RETURNING " in upper:
            rows = await self.conn.fetch(sql, *bound_params)
            return PGCursor(rows, len(rows))

        # asyncpg status strings look like "INSERT 0 1", "UPDATE 2", etc.
        status = await self.conn.execute(sql, *bound_params)
        match = re.fullmatch(
            r"(?:INSERT\s+\d+\s+(\d+)|UPDATE\s+(\d+)|DELETE\s+(\d+)|SELECT\s+(\d+))",
            status.strip(),
            flags=re.IGNORECASE,
        )
        rowcount = int(next(value for value in match.groups() if value is not None)) if match else 0
        return PGCursor([], rowcount)

    async def commit(self):
        # Raw BEGIN transactions are committed through SQL in asyncpg.
        await self.conn.execute("COMMIT")

    async def rollback(self):
        await self.conn.execute("ROLLBACK")

db_pool: asyncpg.Pool | None = None


def asyncpg_connection_args(dsn: str) -> tuple[str, str | None]:
    """Normalize Neon/libpq URLs for asyncpg and require TLS for remote DBs."""
    parts = urlsplit(dsn)
    local = parts.hostname in {"localhost", "127.0.0.1", "::1"}
    query = [
        (key, value)
        for key, value in parse_qsl(parts.query, keep_blank_values=True)
        if key.lower() not in {"sslmode", "channel_binding"}
    ]
    normalized = urlunsplit(
        (parts.scheme, parts.netloc, parts.path, urlencode(query), parts.fragment)
    )
    return normalized, None if local else "require"


@asynccontextmanager
async def db_connect():
    """Acquire one pooled connection and expose the legacy cursor-compatible API."""
    if db_pool is None:
        raise RuntimeError("DATABASE_URL 연결 풀이 초기화되지 않았습니다.")
    async with db_pool.acquire() as conn:
        yield PGConnection(conn)


async def initialize_database() -> dict[str, str]:
    """Create/migrate schema and return persisted activity settings."""
    global db_pool

    database_url = os.getenv("DATABASE_URL", "").strip()
    if not database_url:
        raise RuntimeError(
            "DATABASE_URL 환경변수를 설정해 주세요. Neon PostgreSQL 연결 문자열을 사용해야 합니다."
        )

    pool_min = max(1, int(os.getenv("DB_POOL_MIN", "1")))
    pool_max = max(pool_min, int(os.getenv("DB_POOL_MAX", "5")))
    normalized_dsn, ssl_setting = asyncpg_connection_args(database_url)

    db_pool = await asyncpg.create_pool(
        dsn=normalized_dsn,
        min_size=pool_min,
        max_size=pool_max,
        command_timeout=30,
        ssl=ssl_setting,
    )
    try:
        async with db_pool.acquire() as conn:
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    await conn.execute(statement)

            migrations = (
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS display_name TEXT",
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS display_name_updated_at TEXT",
                "ALTER TABLE messages ADD COLUMN IF NOT EXISTS line_message_id TEXT",
                "ALTER TABLE mentions ADD COLUMN IF NOT EXISTS notification_type TEXT NOT NULL DEFAULT 'mention'",
                "ALTER TABLE mentions ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'pending'",
                "ALTER TABLE mentions ADD COLUMN IF NOT EXISTS processing_token TEXT",
                "ALTER TABLE mentions ADD COLUMN IF NOT EXISTS processing_since TEXT",
                "ALTER TABLE mentions ADD COLUMN IF NOT EXISTS delivered_at TEXT",
                "CREATE INDEX IF NOT EXISTS idx_mentions_pending ON mentions(chat_id, target_id, status, id)",
                "CREATE INDEX IF NOT EXISTS idx_messages_line_id ON messages(chat_id, line_message_id)",
            )
            for statement in migrations:
                await conn.execute(statement)

            old_columns = await conn.fetch(
                """SELECT column_name FROM information_schema.columns
                   WHERE table_schema='public' AND table_name='mentions'"""
            )
            names = {row["column_name"] for row in old_columns}
            if "delivered" in names:
                await conn.execute(
                    """UPDATE mentions
                       SET status = CASE WHEN delivered THEN 'delivered' ELSE 'pending' END
                       WHERE status = 'pending'"""
                )

            settings = await conn.fetch(
                "SELECT key, value FROM bot_metadata WHERE key LIKE 'activity_%'"
            )
            return {row["key"]: row["value"] for row in settings}
    except Exception:
        await db_pool.close()
        db_pool = None
        raise


async def close_pool() -> None:
    """Close the pool during application shutdown."""
    global db_pool
    if db_pool is not None:
        await db_pool.close()
        db_pool = None
